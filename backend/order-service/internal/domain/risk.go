// RiskSignalCategory is the governed vocabulary for risk inputs. Signals are
// deliberately coarse: exact addresses, coordinates, names, phone numbers,
// and other sensitive attributes never enter the decision payload.
type RiskSignalCategory string

const (
	RiskSignalAccount   RiskSignalCategory = "account"
	RiskSignalDevice    RiskSignalCategory = "device"
	RiskSignalPayment   RiskSignalCategory = "payment"
	RiskSignalPromo     RiskSignalCategory = "promo"
	RiskSignalGPS       RiskSignalCategory = "gps"
	RiskSignalHandoff   RiskSignalCategory = "handoff"
	RiskSignalRefund    RiskSignalCategory = "refund"
	RiskSignalClaim     RiskSignalCategory = "claim"
	RiskSignalProvider  RiskSignalCategory = "provider"
	RiskSignalCollusion RiskSignalCategory = "collusion"
)

// RiskDecisionType is the only decision vocabulary exposed to transactional
// callers and operations. It is intentionally independent from order status.
type RiskDecisionType string

const (
	RiskDecisionAllow     RiskDecisionType = "ALLOW"
	RiskDecisionChallenge RiskDecisionType = "CHALLENGE"
	RiskDecisionReview    RiskDecisionType = "REVIEW"
	RiskDecisionHold      RiskDecisionType = "HOLD"
	RiskDecisionBlock     RiskDecisionType = "BLOCK"
)

type RiskOperation string

const (
	RiskOperationOrderCreate          RiskOperation = "order_create"
	RiskOperationFoodOrderCreate      RiskOperation = "food_order_create"
	RiskOperationDispatchAccept       RiskOperation = "dispatch_accept"
	RiskOperationPaymentAuthorization RiskOperation = "payment_authorization"
	RiskOperationRefundRequest        RiskOperation = "refund_request"
	RiskOperationClaimSubmission      RiskOperation = "claim_submission"
	RiskOperationProviderCallback     RiskOperation = "provider_callback"
	RiskOperationHandoffDelivery      RiskOperation = "handoff_delivery"
	RiskOperationPayoutRequest        RiskOperation = "payout_request"
)

type RiskFailureMode string

const (
	RiskFailureNormal       RiskFailureMode = "normal"
	RiskFailureTimeout      RiskFailureMode = "timeout"
	RiskFailureEngineError  RiskFailureMode = "engine_error"
	RiskFailurePersistError RiskFailureMode = "persist_error"
)

var (
	ErrInvalidRiskRequest = errors.New("invalid risk evaluation request")
	ErrInvalidRiskSignal  = errors.New("invalid risk signal")
	validRiskCode         = regexp.MustCompile(`^[a-z0-9][a-z0-9._:-]{1,95}$`)
	validRiskReason       = regexp.MustCompile(`^[a-z0-9][a-z0-9._:-]{1,95}$`)
)

// RiskPolicy is loaded per market and operation from system_configs. The
// defaults are conservative for money/evidence operations and fail-open only
// where a risk outage must not strand a non-financial customer flow.
type RiskPolicy struct {
	MarketCode       string          `json:"market_code"`
	Operation        RiskOperation   `json:"operation"`
	Version          string          `json:"version"`
	TimeoutMillis    int             `json:"timeout_millis"`
	OnTimeout        RiskFailureMode `json:"on_timeout"`
	OnEngineError    RiskFailureMode `json:"on_engine_error"`
	ChallengeScore   float64         `json:"challenge_score"`
	ReviewScore      float64         `json:"review_score"`
	HoldScore        float64         `json:"hold_score"`
	BlockScore       float64         `json:"block_score"`
	SensitiveAllowed bool            `json:"sensitive_attributes_allowed"`
}

func DefaultRiskPolicy(market string, operation RiskOperation) RiskPolicy {
	market = normalizeMarketCode(market)
	failClosed := operation == RiskOperationPaymentAuthorization ||
		operation == RiskOperationRefundRequest ||
		operation == RiskOperationClaimSubmission ||
		operation == RiskOperationProviderCallback ||
		operation == RiskOperationPayoutRequest ||
		operation == RiskOperationHandoffDelivery
	onFailure := RiskFailureMode("fail_open")
	if failClosed {
		onFailure = "fail_closed"
	}
	return RiskPolicy{
		MarketCode:       market,
		Operation:        operation,
		Version:          "risk-rules-2026-09-09-v1",
		TimeoutMillis:    250,
		OnTimeout:        onFailure,
		OnEngineError:    onFailure,
		ChallengeScore:   20,
		ReviewScore:      45,
		HoldScore:        70,
		BlockScore:       90,
		SensitiveAllowed: false,
	}
}

// RiskSignal is an auditable, coarse-grained observation. SubjectKeyHash is
// generated by the service and is never accepted from client input.
type RiskSignal struct {
	Category       RiskSignalCategory `json:"category"`
	Code           string             `json:"code"`
	Score          float64            `json:"score"`
	Source         string             `json:"source"`
	SubjectKeyHash string             `json:"subject_key_hash,omitempty"`
	Attributes     map[string]string  `json:"attributes,omitempty"`
	ObservedAt     time.Time          `json:"observed_at"`
}

