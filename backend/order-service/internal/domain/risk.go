var sensitiveRiskAttributes = map[string]struct{}{
	"age": {}, "address": {}, "date_of_birth": {}, "email": {}, "ethnicity": {},
	"gender": {}, "health": {}, "name": {}, "phone": {}, "religion": {},
	"race": {}, "exact_coordinates": {}, "exact_location": {}, "national_id": {},
}

var allowedRiskAttributes = map[string]struct{}{
	"amount_band": {}, "currency": {}, "device_reputation_band": {}, "gps_integrity": {},
	"handoff_distance_band": {}, "ip_reputation_band": {}, "market_code": {},
	"order_age_band": {}, "provider_code": {}, "service_code": {}, "velocity_band": {},
}

func (r RiskSignal) Validate() error {
	if !validRiskCategory(r.Category) || !validRiskCode.MatchString(strings.TrimSpace(r.Code)) ||
		!validRiskCode.MatchString(strings.TrimSpace(r.Source)) || math.IsNaN(r.Score) || math.IsInf(r.Score, 0) || r.Score < 0 || r.Score > 100 {
		return ErrInvalidRiskSignal
	}
	for key := range r.Attributes {
		key = strings.ToLower(strings.TrimSpace(key))
		if _, forbidden := sensitiveRiskAttributes[key]; forbidden {
			return fmt.Errorf("%w: sensitive attribute %s is not governed", ErrInvalidRiskSignal, key)
		}
		if _, allowed := allowedRiskAttributes[key]; !allowed {
			return fmt.Errorf("%w: attribute %s is not allowlisted", ErrInvalidRiskSignal, key)
		}
	}
	return nil
}

func (r RiskEvaluationRequest) Validate(policy RiskPolicy) error {
	if strings.TrimSpace(string(r.Operation)) == "" || strings.TrimSpace(r.MarketCode) == "" ||
		strings.TrimSpace(r.EntityType) == "" || strings.TrimSpace(r.EntityID) == "" || strings.TrimSpace(r.SubjectID) == "" {
		return ErrInvalidRiskRequest
	}
	if policy.SensitiveAllowed {
		return fmt.Errorf("%w: sensitive attributes cannot be enabled by runtime policy", ErrInvalidRiskRequest)
	}
	for _, signal := range r.Signals {
		if err := signal.Validate(); err != nil {
			return err
		}
	}
	return nil
}

func AssessRisk(request RiskEvaluationRequest, policy RiskPolicy, modelResult *RiskModelResult) (RiskDecision, error) {
	if err := request.Validate(policy); err != nil {
		return RiskDecision{}, err
	}
	allSignals := append([]RiskSignal(nil), request.Signals...)
	if modelResult != nil {
		if math.IsNaN(modelResult.AdditionalScore) || math.IsInf(modelResult.AdditionalScore, 0) || modelResult.AdditionalScore < 0 || modelResult.AdditionalScore > 100 {
			return RiskDecision{}, fmt.Errorf("%w: model score is invalid", ErrInvalidRiskRequest)
		}
		for _, signal := range modelResult.Signals {
			if err := signal.Validate(); err != nil {
				return RiskDecision{}, err
			}
		}
		allSignals = append(allSignals, modelResult.Signals...)
	}

	sort.SliceStable(allSignals, func(i, j int) bool {
		if allSignals[i].Category != allSignals[j].Category {
			return allSignals[i].Category < allSignals[j].Category
		}
		return allSignals[i].Code < allSignals[j].Code
	})

	score := 0.0
	reasons := make([]string, 0, len(allSignals))
	hardBlock := false
	for _, signal := range allSignals {
		score += signal.Score
		reason := standardReasonCode(signal.Category, signal.Code)
		if signal.Score > 0 && !containsString(reasons, reason) {
			reasons = append(reasons, reason)
		}
		if isHardBlockSignal(signal) {
			hardBlock = true
		}
	}
	if modelResult != nil {
		score += modelResult.AdditionalScore
	}
	score = math.Min(math.Max(score, 0), 100)
	decision := decisionForScore(score, policy)
	if hardBlock {
		decision = RiskDecisionBlock
	}
	if len(reasons) == 0 {
		reasons = []string{"risk.no_positive_signal"}
	}
	return RiskDecision{
		Operation:     request.Operation,
		MarketCode:    normalizeMarketCode(request.MarketCode),
		EntityType:    strings.TrimSpace(request.EntityType),
		EntityID:      strings.TrimSpace(request.EntityID),
		Decision:      decision,
		RiskScore:     score,
		ReasonCodes:   reasons,
		Signals:       allSignals,
		PolicyVersion: policy.Version,
		FailureMode:   RiskFailureNormal,
		CorrelationID: strings.TrimSpace(request.CorrelationID),
	}, nil
}

func FallbackRiskDecision(request RiskEvaluationRequest, policy RiskPolicy, mode RiskFailureMode, reason string) RiskDecision {
	decision := RiskDecisionAllow
	if mode == RiskFailureMode("fail_closed") {
		decision = RiskDecisionHold
	}
	return RiskDecision{
		Operation:     request.Operation,
		MarketCode:    normalizeMarketCode(request.MarketCode),
		EntityType:    strings.TrimSpace(request.EntityType),
		EntityID:      strings.TrimSpace(request.EntityID),
		Decision:      decision,
		ReasonCodes:   []string{reason},
		PolicyVersion: policy.Version,
		FailureMode:   mode,
		CorrelationID: strings.TrimSpace(request.CorrelationID),
	}
}

func HashRiskSubject(subject string) string {
	key := strings.TrimSpace(os.Getenv("RISK_PSEUDONYM_KEY"))
	if key == "" {
		key = strings.TrimSpace(os.Getenv("EVENT_ACTOR_PSEUDONYM_KEY"))
	}
	if key == "" {
		sum := sha256.Sum256([]byte(subject))
		return hex.EncodeToString(sum[:])
	}
	mac := hmac.New(sha256.New, []byte(key))
	_, _ = mac.Write([]byte(subject))
	return hex.EncodeToString(mac.Sum(nil))
}

func normalizeMarketCode(market string) string {
	market = strings.ToLower(strings.TrimSpace(market))
	if market == "" {
		return "id-jk"
	}
	return market
}

func validRiskCategory(category RiskSignalCategory) bool {
	switch category {
	case RiskSignalAccount, RiskSignalDevice, RiskSignalPayment, RiskSignalPromo, RiskSignalGPS,
		RiskSignalHandoff, RiskSignalRefund, RiskSignalClaim, RiskSignalProvider, RiskSignalCollusion:
		return true
	default:
		return false
	}
}

func decisionForScore(score float64, policy RiskPolicy) RiskDecisionType {
	switch {
	case score >= policy.BlockScore:
		return RiskDecisionBlock
	case score >= policy.HoldScore:
		return RiskDecisionHold
	case score >= policy.ReviewScore:
		return RiskDecisionReview
	case score >= policy.ChallengeScore:
		return RiskDecisionChallenge
	default:
		return RiskDecisionAllow
	}
}

func isHardBlockSignal(signal RiskSignal) bool {
	switch strings.ToLower(strings.TrimSpace(signal.Code)) {
	case "account.suspended", "device.blocked", "payment.provider_invalid", "provider.webhook_invalid", "collusion.confirmed", "gps.spoof_confirmed":
		return true
	default:
		return false
	}
}

func standardReasonCode(category RiskSignalCategory, code string) string {
	code = strings.ToLower(strings.TrimSpace(code))
	if validRiskReason.MatchString(code) {
		return "risk." + code
	}
	return "risk." + string(category) + ".signal"
}

func containsString(values []string, target string) bool {
	for _, value := range values {
		if value == target {
			return true
		}
	}
	return false
}

func RiskReviewRequired(decision RiskDecisionType) bool {
	return decision == RiskDecisionReview || decision == RiskDecisionHold
}
